const storedLanguage = localStorage.getItem(STORAGE_KEY);
let currentLanguage = Object.hasOwn(MESSAGES, storedLanguage) ? storedLanguage : 'id';

export function getLanguage() {
  return currentLanguage;
}

export function t(key, values = {}) {
  const message = MESSAGES[currentLanguage][key];
  if (message === undefined) throw new Error(`Missing ${currentLanguage} translation: ${key}`);
  return message.replace(/\{(\w+)\}/g, (_match, name) => {
    if (!(name in values)) throw new Error(`Missing value "${name}" for translation: ${key}`);
    return String(values[name]);
  });
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-html]').forEach((element) => {
    element.innerHTML = t(element.dataset.i18nHtml);
  });
  for (const [attribute, dataAttribute] of [
    ['aria-label', 'i18nAriaLabel'],
    ['title', 'i18nTitle'],
  ]) {
    root.querySelectorAll(`[data-${dataAttribute.replace(/[A-Z]/g, (match) => `-${match.toLowerCase()}`)}]`).forEach((element) => {
      element.setAttribute(attribute, t(element.dataset[dataAttribute]));
    });
  }
  document.documentElement.lang = currentLanguage;
  document.title = t('app.title');
}

export function setLanguage(language) {
  if (!Object.hasOwn(MESSAGES, language)) throw new RangeError(`Unsupported language: ${language}`);
  if (language === currentLanguage) return;
  currentLanguage = language;
  localStorage.setItem(STORAGE_KEY, language);
  applyTranslations();
  document.dispatchEvent(new Event('app-language-change'));
}
